// Regenerates overlay.html (the moosematrix reference copy of the markup).
// tests/overlay.test.mjs fails if the checked-in file drifts from renderOverlay().
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { renderOverlay } from "../overlay.mjs";

export const HEADER = "<!-- @moosematrix/search 0.1.0 — generated by scripts/write-overlay.mjs from overlay.mjs (site=moosematrix). Do not edit. -->\n";
export const reference = () => HEADER + renderOverlay({ site: "moosematrix" });

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(new URL("../overlay.html", import.meta.url), reference());
  console.log("wrote overlay.html");
}
