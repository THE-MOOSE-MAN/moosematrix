// Builds demo/index.html from the three partials and the hashed theme-init (first child of <head>), so the demo always matches what ships.
// Plain Node, no dependencies. CI rebuilds it and fails if the committed file differs.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const pkg = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (f) => readFileSync(join(pkg, f), "utf8");
const { version } = JSON.parse(read("package.json"));

const indent = (html, pad) =>
  html
    .trimEnd()
    .split("\n")
    .map((line) => (line ? pad + line : line))
    .join("\n");

const header = read("header.html");
const { current: themeInit } = JSON.parse(read("hashed/manifest.json"));
const footer = read("footer.html");
// The demo serves its own clearly labelled sample index next to the page.
const search = read("search.html").replace('data-mm-index="/search-index.json"', 'data-mm-index="search-index.json"');

const swatches = [
  "ground", "panel", "panel-2", "ink", "ink-2", "accent", "accent-fill",
  "on-accent", "edge", "rule", "money", "store", "selection",
]
  .map((t) => `          <li class="demo-swatch demo-swatch--${t}"><span class="demo-chip"></span><code>--mm-color-${t}</code></li>`)
  .join("\n");

const out = `<!doctype html>
<!-- GENERATED by scripts/build-demo.mjs from header.html, search.html and footer.html. Do not edit by hand. -->
<html lang="en">
  <head>
    <script src="../hashed/${themeInit}"></script>
    <meta charset="utf-8">
    <meta name="viewport" content="width=device-width, initial-scale=1">
    <meta name="color-scheme" content="dark">
    <meta name="theme-color" content="#070b13">
    <meta name="robots" content="noindex">
    <meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'self'; style-src 'self'; font-src 'self'; img-src 'self'; connect-src 'self'; base-uri 'none'; form-action https://moosematrix.com">
    <title>@moosematrix/tokens ${version} demo</title>
    <link rel="icon" href="../brand/main-icon-light.svg" type="image/svg+xml">
    <link rel="preload" href="../fonts/IBMPlexSans-Regular-Latin1.woff2" as="font" type="font/woff2" crossorigin>
    <link rel="preload" href="../fonts/BarlowCondensed-ExtraBold-Latin1.woff2" as="font" type="font/woff2" crossorigin>
    <link rel="stylesheet" href="../fonts.css">
    <link rel="stylesheet" href="../tokens.css">
    <link rel="stylesheet" href="../header.css">
    <link rel="stylesheet" href="../search.css">
    <link rel="stylesheet" href="../footer.css">
    <link rel="stylesheet" href="demo.css">
    <script src="../nav.js" defer></script>
    <script src="../search.js" defer></script>
  </head>
  <body class="demo">
${indent(header, "    ")}
    <main id="main" class="mm-shell demo-main">
      <p class="mm-micro demo-eyebrow">Demo · @moosematrix/tokens ${version}</p>
      <h1 class="demo-title">Design tokens</h1>
      <p class="demo-lede">This page exercises the shared header, search overlay and footer. Search uses a small sample index (demo/search-index.json), not real site content.</p>
      <section aria-labelledby="demo-colours">
        <h2 id="demo-colours" class="demo-h2">Colours</h2>
        <ul class="demo-swatches">
${swatches}
        </ul>
      </section>
      <section aria-labelledby="demo-type">
        <h2 id="demo-type" class="demo-h2">Type</h2>
        <p class="demo-display">Barlow Condensed 800</p>
        <p>IBM Plex Sans 400, the body face. <strong>Bold is 700.</strong> <a class="demo-link" href="#demo-type">An inline link</a>.</p>
        <p><code>IBM Plex Mono 400 for code and labels</code></p>
        <p class="demo-money">Money green</p>
        <p class="demo-store">Store blue</p>
      </section>
    </main>
${indent(search, "    ")}
${indent(footer, "    ")}
  </body>
</html>
`;

writeFileSync(join(pkg, "demo", "index.html"), out);
console.log("wrote demo/index.html");
